import { performance } from "node:perf_hooks";
const DEPS = process.argv[2];
const t0 = performance.now();
const B = await import(`file://${DEPS}/node_modules/brepjs/dist/brepjs.js`);
const { OcctKernel } = await import(`file://${DEPS}/node_modules/occt-wasm/dist/index.js`);
const kernel = await OcctKernel.init();
B.registerKernel('occt-wasm', B.OcctWasmAdapter.fromKernel(kernel));
console.log("init ms", (performance.now()-t0).toFixed(0));
const b = B.box(20, 10, 5);
console.log("box valid", B.isValid(b), "vol", B.measureVolume(b), "bounds", JSON.stringify(B.getBounds(b)));
const bc = B.box(20,10,5,{centered:true});
console.log("centered bounds", JSON.stringify(B.getBounds(bc)));
const c = B.cylinder(5, 10);
console.log("cyl bounds", JSON.stringify(B.getBounds(c)));
const cn = B.cone(5, 3, 10);
console.log("cone vol", B.measureVolume(cn), JSON.stringify(B.getBounds(cn)));
const d = B.describe(b); console.log("describe", JSON.stringify(d));
const r = B.cut(b, B.cylinder(2, 20, {at:[10,5,-1]}));
console.log("cut result keys", Object.keys(r), r.ok);
const e = B.edgeFinder().inDirection('Z').findAll(b); console.log("vertical edges", e.length);
const f = B.fillet(b, e, 1); console.log("fillet ok", f.ok, f.ok && B.measureVolume(f.value));
const dr = B.drawRoundedRectangle(20, 10, 2); console.log("drawing bbox", JSON.stringify(dr.boundingBox?.repr ?? null));
const sk = dr.sketchOnPlane("XY"); console.log("sketch methods", Object.getOwnPropertyNames(Object.getPrototypeOf(sk)).join(","));
const ex = sk.extrude(10); console.log("extrude type", ex?.constructor?.name, Object.keys(ex).slice(0,5), B.measureVolume(ex));
