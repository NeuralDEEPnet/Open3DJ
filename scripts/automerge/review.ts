// Pure helpers for the advisory AI review (.github/workflows/ai-review.yml): preparing the
// untrusted input the reviewer reads, validating its structured output, and rendering the
// one comment the bot posts. Everything that came from a pull request is treated as data.
import { createHash } from "node:crypto";

export const COMMENT_MARKER = "<!-- open3dj-ai-review -->";
/** A hidden line in the bot's comment that records when each review ran, for the daily budget. */
export const LOG_PREFIX = "<!-- open3dj-ai-review-log:";
export const ATTRIBUTION = "Generated by [neuraldeep.net design agents](https://www.neuraldeep.net)";

export type Verdict = "pass" | "changes-suggested";
export type Severity = "blocker" | "suggestion" | "nit";

export interface Finding {
  path: string;
  severity: Severity;
  note: string;
}

export interface ReviewOutput {
  verdict: Verdict;
  summary: string;
  findings: Finding[];
}

// Zero-width, bidirectional and other invisible format characters (Trojan Source, hidden prompts).
const INVISIBLE = /[­؜᠎​-‏‪-‮⁠-⁤⁦-⁯﻿￹-￻]|\udb40[\udc00-\udc7f]/g;

/** Make invisible characters visible as [U+XXXX] so the reviewer sees them, and drop other control characters. */
export function revealInvisible(text: string): string {
  return text
    .replace(INVISIBLE, (c) => `[U+${(c.codePointAt(0) ?? 0).toString(16).toUpperCase().padStart(4, "0")}]`)
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, "");
}

export interface PatchFile {
  filename: string;
  status: string;
  previous_filename?: string;
  patch?: string;
}

/** A unified-diff-like text of the pull request, capped at maxChars, invisible characters revealed. */
export function buildDiff(files: PatchFile[], maxChars: number): { text: string; truncated: boolean } {
  let out = "";
  let truncated = false;
  for (const f of files) {
    const head = `=== ${f.status}: ${f.previous_filename ? `${f.previous_filename} -> ` : ""}${f.filename}\n`;
    const body = f.patch === undefined ? "(no text diff: binary or too large)\n" : `${f.patch}\n`;
    const chunk = revealInvisible(head + body);
    if (out.length + chunk.length > maxChars) {
      out += chunk.slice(0, Math.max(0, maxChars - out.length));
      out += "\n=== (diff truncated here)\n";
      truncated = true;
      break;
    }
    out += chunk;
  }
  return { text: out, truncated };
}

/** Cut a string to at most maxBytes of UTF-8 without splitting a character. */
export function truncateBytes(text: string, maxBytes: number): { text: string; truncated: boolean } {
  if (Buffer.byteLength(text, "utf8") <= maxBytes) return { text, truncated: false };
  let out = Buffer.from(text, "utf8").subarray(0, maxBytes).toString("utf8");
  if (out.endsWith("\uFFFD")) out = out.slice(0, -1);
  return { text: out, truncated: true };
}

/**
 * A short fingerprint of a changed-file list (path, old path, status and blob), so a verdict
 * given for one set of changes is never applied to another.
 */
export function filesFingerprint(files: Array<{ filename: string; status: string; previous_filename?: string; sha?: string | null }>): string {
  const rows = files.map((f) => [f.filename, f.previous_filename ?? "", f.status, f.sha ?? ""].join("\u0000")).sort();
  return createHash("sha256").update(rows.join("\n")).digest("hex").slice(0, 16);
}

/** The fingerprint written into an ai-review status description, or undefined. */
export function fingerprintInStatus(description: string): string | undefined {
  return /\bfiles ([0-9a-f]{16})\b/.exec(description)?.[1];
}

/** Review times recorded in the bot's comment. */
export function reviewLog(body: string): Date[] {
  const line = body.split("\n").find((l) => l.startsWith(LOG_PREFIX));
  if (!line) return [];
  return line.slice(LOG_PREFIX.length).replace(/-->\s*$/, "").split(",").map((s) => new Date(s.trim())).filter((d) => !Number.isNaN(d.getTime()));
}

export function renderReviewLog(times: Date[]): string {
  return `${LOG_PREFIX} ${times.slice(-20).map((d) => d.toISOString()).join(",")} -->`;
}

// Text that looks like a credential. The reviewer has no tools and never sees a secret, so
// this is a second guard: a match makes the review an error instead of a public comment.
const CREDENTIAL_PATTERNS: RegExp[] = [
  /sk-ant-/i,
  /\bgh[opsur]_[A-Za-z0-9]{20,}/,
  /github_pat_/i,
  /-----BEGIN [A-Z ]*PRIVATE KEY/,
  /\bAKIA[0-9A-Z]{16}\b/,
  /\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}/, // a JSON web token
  /\b[0-9a-f]{41,}\b/i, // a hex run longer than a commit id
  /(?:[A-Za-z0-9+/=][\s.,;:|_-]{1,3}){24,}[A-Za-z0-9+/=]/, // 25 or more single characters with separators between them
];

/** True when a run of 40 or more base64 characters mixes upper case, lower case and digits. */
function hasHighEntropyRun(text: string): boolean {
  for (const m of text.matchAll(/[A-Za-z0-9+/=]{40,}/g)) {
    const r = m[0];
    if (/[a-z]/.test(r) && /[A-Z]/.test(r) && /[0-9]/.test(r)) return true;
  }
  return false;
}

/** True when the text looks like it holds a credential, plain or spaced out. */
export function looksLikeCredential(text: string): boolean {
  if (CREDENTIAL_PATTERNS.some((re) => re.test(text)) || hasHighEntropyRun(text)) return true;
  // The same with separators removed, for prefixes that prose never contains.
  const compact = text.replace(/[\s.,;:|_\-'"`*()[\]{}<>\\/]+/g, "");
  return /skant(?:api|oat|admin)\d\d/i.test(compact) || /githubpat\d/i.test(compact);
}

/** Parse and check the reviewer's structured output. Throws on anything unexpected. */
export function parseReviewOutput(raw: string): ReviewOutput {
  const o = JSON.parse(raw) as Partial<ReviewOutput>;
  if (o.verdict !== "pass" && o.verdict !== "changes-suggested") throw new Error("verdict must be pass or changes-suggested");
  if (typeof o.summary !== "string" || o.summary.trim() === "") throw new Error("summary must be a non-empty string");
  const findings = o.findings ?? [];
  if (!Array.isArray(findings)) throw new Error("findings must be a list");
  const clean: Finding[] = [];
  for (const f of findings.slice(0, 10)) {
    if (!f || typeof f.note !== "string") throw new Error("each finding needs a note");
    const severity: Severity = f.severity === "blocker" || f.severity === "nit" ? f.severity : "suggestion";
    clean.push({ path: typeof f.path === "string" ? f.path : "", severity, note: f.note });
  }
  if ([o.summary, ...clean.flatMap((f) => [f.path, f.note])].some(looksLikeCredential)) {
    throw new Error("the review output looks like it contains a credential, so it was not posted");
  }
  // A blocker always means changes are suggested, whatever the verdict says.
  const verdict: Verdict = clean.some((f) => f.severity === "blocker") ? "changes-suggested" : o.verdict;
  return { verdict, summary: o.summary, findings: clean };
}

/**
 * Plain text safe to put in a public comment: no HTML, no links, images or mentions, no
 * markdown structure, so text steered by a pull request cannot ping people or phish.
 */
export function safeText(s: string, max: number): string {
  let t = revealInvisible(s).replace(/\r\n?/g, "\n").replace(/\n{3,}/g, "\n\n").trim();
  if (t.length > max) t = `${t.slice(0, max - 3)}...`;
  t = t.replace(/[\\`*_{}[\]()<>#|!~&]/g, (c) => `\\${c}`);
  t = t.replace(/@/g, "@​"); // breaks @mentions and team pings
  t = t.replace(/:\/\//g, ":/​/"); // breaks autolinked URLs
  return t;
}

export function renderComment(r: ReviewOutput, ctx: { headSha: string; lane: string; log?: Date[] }): string {
  const verdict = r.verdict === "pass" ? "pass" : "changes suggested";
  const lines = [
    COMMENT_MARKER,
    ...(ctx.log && ctx.log.length > 0 ? [renderReviewLog(ctx.log)] : []),
    `### AI review (advisory): ${verdict}`,
    "",
    `Reviewed commit ${ctx.headSha.slice(0, 12)}. Merge lane: ${safeText(ctx.lane, 20)}.`,
    "",
    safeText(r.summary, 1500),
  ];
  if (r.findings.length > 0) {
    lines.push("");
    for (const f of r.findings) {
      const where = f.path ? ` (${safeText(f.path, 200)})` : "";
      lines.push(`- **${f.severity}**${where}: ${safeText(f.note, 600).replace(/\n+/g, " ")}`);
    }
  }
  lines.push(
    "",
    "This review is automatic and advisory. It reads only the diff and treats the pull request's text as data. A maintainer can override it, and the label it sets only matters for the auto lane.",
    "",
    ATTRIBUTION,
  );
  return lines.join("\n");
}
